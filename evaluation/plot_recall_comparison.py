"""Plot measured VecMapLocNet/TopVecLoc recalls, in a single four-panel row."""
import argparse
import json
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.ticker import PercentFormatter
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PANELS = [('position','m','Position (m)'), ('yaw','deg','Yaw (°)'),
          ('longitudinal','m','Longitudinal (m)'), ('lateral','m','Lateral (m)')]
THRESHOLDS = [1,3,5,10]


def read_source(path, variants=('VecMapLocNet_released','none')):
    frame = pd.read_csv(path).set_index('variant').loc[list(variants)].reset_index()
    if not frame['sample_count'].eq(10000).all():
        raise ValueError('Expected 10000 test images for every setting')
    for family,unit,_ in PANELS:
        values = frame[[f'{family}_recall_{t}{unit}' for t in THRESHOLDS]].to_numpy(float)
        if not np.isfinite(values).all() or (values<0).any() or (values>100).any():
            raise ValueError('Invalid percentage recall')
        if (np.diff(values,axis=1)<0).any():
            raise ValueError('Recall must be nondecreasing with threshold')
    return frame


def build_figure(data, styles=None, figsize=(16,5.2), legend_columns=2):
    plt.rcParams.update({'font.family':'STIXGeneral','font.size':16,
        'font.weight':'normal','axes.labelweight':'normal','axes.linewidth':1,
        'axes.edgecolor':'#44494D','axes.labelcolor':'#252A2D',
        'xtick.color':'#33383C','ytick.color':'#33383C',
        'svg.fonttype':'none','pdf.fonttype':42,'savefig.facecolor':'white'})
    fig,axes = plt.subplots(1,4,figsize=figsize)
    fig.subplots_adjust(left=.065,right=.99,bottom=.22,
                        top=.80 if len(data)>2 else .83,wspace=.31)
    if styles is None:
        styles = [('VecMapLocNet','#D85C5C','-','o'),
                  ('TopVecLoc (ours)','#179EAA','-','D')]
    if len(styles) != len(data):
        raise ValueError('Every data row must have its own style')
    x = np.arange(4)
    for i,(ax,(family,unit,title)) in enumerate(zip(axes,PANELS)):
        for row,(label,color,linestyle,marker) in zip(data.itertuples(index=False),styles):
            values = [getattr(row,f'{family}_recall_{t}{unit}') for t in THRESHOLDS]
            ax.plot(x,values,label=label,color=color,linestyle=linestyle,
                    linewidth=1.65 if len(data)>2 else 2.4,marker=marker,
                    markersize=6 if len(data)>2 else 7.5,
                    markerfacecolor='white' if marker=='o' else color,
                    markeredgewidth=1.5,solid_capstyle='round',clip_on=False)
        ax.set_xlim(-.2,3.2)
        ax.set_ylim(0,100)
        ax.set_xticks(x,['R@1','R@3','R@5','R@10'])
        ax.set_yticks(np.arange(0,101,20))
        ax.yaxis.set_major_formatter(PercentFormatter(xmax=100,decimals=0))
        ax.set_ylabel('Recall (%)',fontsize=17,labelpad=4)
        ax.grid(True,axis='y',which='major',color='#E8EBED',linestyle='-',linewidth=.55)
        ax.set_axisbelow(True)
        ax.tick_params(direction='in',top=True,right=True,length=3.5,width=.85,pad=6)
        ax.text(.5,-.21,f'({chr(97+i)}) {title}',ha='center',va='top',
                transform=ax.transAxes,fontsize=17,fontweight='normal',color='#252A2D')
    handles,labels = axes[0].get_legend_handles_labels()
    legend = fig.legend(handles,labels,loc='upper center',bbox_to_anchor=(.525,.995),
        ncol=legend_columns,fontsize=14 if len(data)>2 else 17,
        frameon=True,fancybox=True,facecolor='white',edgecolor='#D6DCDF',
        handlelength=2.7,handletextpad=.75,columnspacing=3,borderpad=.65)
    legend.get_frame().set_linewidth(.8)
    return fig,axes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=ROOT/'experiments/inference_interventions/full_v1/comparison.csv')
    parser.add_argument('--output',type=Path,default=ROOT/'figures/recall_comparison_1x4')
    args = parser.parse_args()
    if args.output.exists():
        raise FileExistsError(f'Refusing to overwrite figure bundle: {args.output}')
    data = read_source(args.source)
    fig,_ = build_figure(data)
    args.output.mkdir(parents=True)
    data.to_csv(args.output/'source_data.csv',index=False)
    stem = args.output/'vecmaplocnet_topvecloc_recall'
    fig.savefig(stem.with_suffix('.png'),dpi=600)
    fig.savefig(stem.with_suffix('.tiff'),dpi=600,pil_kwargs={'compression':'tiff_lzw'})
    fig.savefig(stem.with_suffix('.pdf'))
    fig.savefig(stem.with_suffix('.svg'))
    # The QA preview is generated by the same Python backend as the final artwork.
    fig.savefig(args.output/'preview.png',dpi=150)
    plt.close(fig)
    notes = dict(archetype='quantitative grid',backend='Python/matplotlib',
        conclusion='Describe measured baseline/current-model trade-offs across thresholds; not uniform dominance.',
        panel_order=[title for _,_,title in PANELS],dpi=600,dimensions_inches=[16,5.2],
        styling='Coral red / cyan-teal, solid lines, hollow circles / filled diamonds; shared legend above all panels',
        test_city='SanFrancisco',n_per_method=10000,
        metric='Maximum-probability pose, strict < threshold; recall in percent.',
        position_unit='meters',yaw_unit='degrees; wrapped absolute angular error',
        baseline='Released VecMapLocNet checkpoint, provenance confirmed by user.',
        topvecloc='Previously selected current checkpoint; test-subset selection limits independent validation.',
        uncertainty='Point estimates only; no multi-seed runs or confidence intervals supplied.',
        image_integrity='No synthetic values, smoothing, truncated y axes or selective sample removal.')
    (args.output/'figure_notes.json').write_text(json.dumps(notes,indent=2)+'\n')
    print(stem.with_suffix('.png'))


if __name__ == '__main__':
    main()
